#define FM_2PI ((float)(2.0f * M_PI))	/*!< \brief definition of 2 times Pi (2*3.14159...) */
#define FM_PI ((float)M_PI)				/*!< \brief definition Pi */
#define FM_PI_2 ((float)(0.5f * M_PI))	/*!< \brief definition Pi/2 (2*3.14159...) */
#define FM_PI_4 ((float)(0.25f * M_PI)) /*!< \brief definition of Pi/4 (2*3.14159...) */

#define FLT_EPSILON 0.0000001f

#define F 0.28f

float _atan_(float y, float x, float offset)
{
	float result;
	float y2 = y * y;
	float x2 = x * x;

	if(y2 <= x2)
	{
		/* |y/x| <= 1 */
		result = x * y / (x2 + F * y2);
	}
	else
	{
		union
		{
			float f;
			uint32_t i;
		} yu, xu;

		xu.f = x;
		yu.f = y;
		if((xu.i ^ yu.i) & 0x80000000)
		{
			/* |y/x| < -1 */
			result = -FM_PI_2 - x * y / (y2 + F * x2);
		}
		else
		{
			/* |y/x| > +1 */
			result = +FM_PI_2 - x * y / (y2 + F * x2);
		}
	}
	return result + offset;
}

float _atan2_(float y, float x)
{
	float result;

	if(x > FLT_EPSILON)
	{
		result = _atan_(y, x, 0.0f);
	}
	else if(x < -FLT_EPSILON)
	{
		if(y >= 0.0f)
		{
			result = _atan_(y, x, FM_PI);
		}
		else /* y < 0.0 */
		{
			result = _atan_(y, x, -FM_PI);
		}
	}
	else /* x == 0.0 */
	{
		if(y > FLT_EPSILON)
		{
			result = FM_PI_2;
		}
		else if(y < -FLT_EPSILON)
		{
			result = -FM_PI_2;
		}
		else /* y == 0.0 */
		{
			result = 0.0f;
		}
	}
	return result;
}

/*
a := min (|x|, |y|) / max (|x|, |y|)
s := a * a
r := ((-0.0464964749 * s + 0.15931422) * s - 0.327622764) * s * a + a
if |y| > |x| then r := 1.57079637 - r
if x < 0 then r := 3.14159274 - r
if y < 0 then r := -r
 *
 */
float _atan2_a(float y, float x)
{
	float d, a, s, r;

	d = MAX(ABS(x), ABS(y));

	if(d < FLT_EPSILON)
	{
		return 0;
	}

	a = MIN(ABS(x), ABS(y)) / MAX(ABS(x), ABS(y));
	s = a * a;
	r = ((-0.0464964749f * s + 0.15931422f) * s - 0.327622764f) * s * a + a;

	if(ABS(y) > ABS(x))
	{
		r = 0.5f * M_PI - r;
	}
	if(x < 0)
	{
		r = M_PI - r;
	}
	if(y < 0)
	{
		r = -r;
	}
	return r;
}

float _sqrt_(float a)
{
	return sqrt(a);
}

