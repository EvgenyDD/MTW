float _sin_(float x)
{
	float result, sign = 1.0f, scale;
	float a, b;
	uint32_t idx;

	/* make result positive */
	if(x < 0.0f)
	{
		sign = -sign;
		x = -x;
	}

	/* bring results into range [0;2*pi] */
	scale = FM_2PI;
	while(x > scale)
	{
		x -= scale;
		scale += scale;
	}

	/* exploid symmetries */
	if(x > FM_PI)
	{
		sign = -sign;
		x -= FM_PI;
	}
	if(x > FM_PI_2)
	{
		x = FM_PI - x;
	}

	/* now, we can assume x : [0;pi/2] */
	idx = (int)(x * (128.00f / FM_PI_2));
	a = sin_table[idx].a;
	b = sin_table[idx].b;
	result = a * x + b;

	/* apply sign */
	result *= sign;

	return result;
}

float _cos_(float x)
{
	return _sin_(x + FM_PI_2);
}

void _sin_cos_(float x, float *s, float *c)
{
	float ssign = 1.0f, csign = 1.0f, scale;
	float a, b;
	uint32_t idx;

	/* make result positive */
	if(x < 0.0f)
	{
		ssign = -1.0f;
		x = -x;
	}

	/* bring results into range [0;2*pi] */
	scale = FM_2PI;
	while(x > scale)
	{
		x -= scale;
		scale += scale;
	}

	if(x > FM_PI)
	{
		ssign = -ssign;
		csign = -1.0f;
		x -= FM_PI;
	}
	if(x > FM_PI_2)
	{
		x = FM_PI - x;
		csign = -csign;
	}

	idx = (int)(x * (128.00f / FM_PI_2));
	a = sin_table[idx].a;
	b = sin_table[idx].b;
	*s = a * x + b;
	*s *= ssign;

	idx = 127 - idx;
	a = sin_table[idx].a;
	b = sin_table[idx].b;
	*c = a * (FM_PI_2 - x) + b;
	*c *= csign;
}
